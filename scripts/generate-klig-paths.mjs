import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Converts the "k-lig" wordmark (Sanal Lig'in yerini alan marka adı, Canlı
// oyun eklendikten sonra "Sanal" artık doğru olmadığından) into static SVG
// glyph outlines — LogoMark.tsx'teki aynı yöntem (Caveat Bold, opentype.js
// ile trace edilip build-time'da path verisine çevriliyor), ama bağımsız
// bir bileşen (KLigMark.tsx): logonun altındaki swash/underline'ı taşımıyor,
// yalnızca "k-lig" metnini logoyla aynı fontta/renkte gösteriyor. Kullanım
// yeri (Sanal Lig sıralama tablosunun başlığı gibi) LogoMark'ın 1400 birimlik
// geniş tuval/letter-spacing'ine ihtiyaç duymadığından ayrı, daha kompakt bir
// geometriyle üretiliyor — logo-geometry.mjs'i paylaşmıyor (bilinçli).

const TEXT = 'k-lig';
const LOGO_COLOR = '#2563EB';
const FONT_SIZE = 280;
const LETTER_SPACING = 6;
const PAD = 20;

const fontPath = join(__dirname, '../node_modules/@fontsource/caveat/files/caveat-latin-700-normal.woff');
const fontBuffer = readFileSync(fontPath);
const fontArrayBuffer = fontBuffer.buffer.slice(fontBuffer.byteOffset, fontBuffer.byteOffset + fontBuffer.byteLength);
const font = opentype.parse(fontArrayBuffer);

const letterSpacingOption = { letterSpacing: LETTER_SPACING / FONT_SIZE };
const textPath = font.getPath(TEXT, 0, 0, FONT_SIZE, letterSpacingOption);
// opentype.js'in toPathData'sındaki ondalık yuvarlama (`roundDecimal`) bir
// string-exponent hilesi kullanıyor (`decimalPart + "e+" + places`) — bazı
// glyph noktalarının kalıntı float gürültüsü (ör. 5e-15) bilimsel
// gösterime düştüğünde bu string'i bozup "NaN" üretiyor. Kalıntı gürültüyü
// toPathData'ya varmadan temizlemek için komutlardaki her koordinatı elle
// önceden yuvarlıyoruz — offset'ten (0,0 dahil) bağımsız, kalıcı bir çözüm
// (generate-logo-paths.mjs bunu büyük bir startX/TEXT_Y ofsetinin tesadüfen
// gürültüyü maskelemesiyle atlatıyordu, "k-lig" gibi daha kısa/farklı bir
// metinde aynı şans tutmadı — 'k-lig' orada 0,0'da olduğu gibi 300,300'de
// de NaN üretti, bu yüzden kaynağı doğrudan düzeltmek gerekti).
for (const cmd of textPath.commands) {
  for (const key of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) {
    if (typeof cmd[key] === 'number') cmd[key] = Number(cmd[key].toFixed(6));
  }
}
const textPathData = textPath.toPathData(2);
if (textPathData.includes('NaN')) {
  throw new Error('Generated path still contains NaN after rounding — investigate before shipping.');
}
const bbox = textPath.getBoundingBox();

const viewBox = [
  (bbox.x1 - PAD).toFixed(2),
  (bbox.y1 - PAD).toFixed(2),
  (bbox.x2 - bbox.x1 + PAD * 2).toFixed(2),
  (bbox.y2 - bbox.y1 + PAD * 2).toFixed(2),
].join(' ');

const tsx = `// AUTO-GENERATED by scripts/generate-klig-paths.mjs — do not hand-edit.
// "k-lig" wordmark (Sanal Lig'in yeni adı — Canlı oyun eklendikten sonra
// "Sanal" artık doğru olmadığından) LogoMark.tsx ile aynı yöntemle (Caveat
// Bold, opentype.js) statik SVG glyph outline'larına çevrildi — ayrı bir
// bileşen çünkü LogoMark'ın altındaki swash/underline'ı taşımıyor,
// yalnızca metni logoyla aynı fontta/renkte gösteriyor.
export const KLIG_VIEW_BOX = '${viewBox}';
export const KLIG_TEXT_PATH = '${textPathData}';
export const KLIG_COLOR = '${LOGO_COLOR}';

interface KLigMarkProps {
  /** Sabit piksel (ör. 22) ya da akıcı bir CSS boyutu (ör. clamp(...)). */
  height: number | string;
  color?: string;
  className?: string;
}

export function KLigMark({ height, color = KLIG_COLOR, className }: KLigMarkProps) {
  const [, , vbWidth, vbHeight] = KLIG_VIEW_BOX.split(' ').map(Number);
  const isFluid = typeof height === 'string';
  const width = isFluid ? undefined : (height * vbWidth) / vbHeight;
  return (
    <svg
      width={isFluid ? undefined : width}
      height={isFluid ? undefined : height}
      viewBox={KLIG_VIEW_BOX}
      fill="none"
      aria-hidden="true"
      className={className}
      style={isFluid ? { height, width: 'auto', aspectRatio: vbWidth + ' / ' + vbHeight } : undefined}
    >
      <path d={KLIG_TEXT_PATH} fill={color} />
    </svg>
  );
}
`;

writeFileSync(join(__dirname, '../src/components/KLigMark.tsx'), tsx);
console.log('✓ src/components/KLigMark.tsx ("k-lig" wordmark, no font dependency)');

// Flutter portu aynı wordmark'ı aynı kaynaktan alır (generate-logo-paths.mjs
// ile birebir aynı desen, bkz. mobile/CLAUDE.md) — path verisi burada Dart
// sabitlerine de yazılır ki marka yeniden üretildiğinde iki taraf
// kendiliğinden senkron kalsın.
const dart = `// AUTO-GENERATED by scripts/generate-klig-paths.mjs — do not hand-edit.
// "k-lig" wordmark path verisi — web KLigMark.tsx ile AYNI üreticiden
// (Caveat Bold glyph outline'ları). Çizim: klig_mark.dart.

const String kligViewBox = '${viewBox}';
const String kligTextPath = '${textPathData}';
const int kligColorValue = 0xFF${LOGO_COLOR.slice(1)};
`;

writeFileSync(
  join(__dirname, '../mobile/app/lib/src/ui/score/klig_mark_data.dart'),
  dart,
);
console.log('✓ mobile/app/lib/src/ui/score/klig_mark_data.dart (same wordmark for Flutter)');
